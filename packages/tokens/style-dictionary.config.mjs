import StyleDictionary from 'style-dictionary'

const flat = tokens => tokens.allTokens.map(t => ({
  name: t.path.join('.'),
  cssVar: `--${t.name}`,
  value: String(t.$value ?? t.value),
  type: t.$type ?? t.type ?? 'other',
  ...(t.$description ?? t.comment ? { description: t.$description ?? t.comment } : {}),
}))

StyleDictionary.registerFormat({
  name: 'css/cab-variables',
  format: ({ dictionary }) => {
    const v = dictionary.allTokens.map(t => `  --${t.name}: ${t.$value ?? t.value};`).join('\n')
    const rm = dictionary.allTokens
      .filter(t => t.$extensions?.['cab.reducedMotion'] !== undefined)
      .map(t => `    --${t.name}: ${t.$extensions['cab.reducedMotion']};`).join('\n')
    return `/* Generated by Style Dictionary. Do not edit. */\n:root {\n${v}\n}\n\n@media (prefers-reduced-motion: reduce) {\n  :root {\n${rm}\n  }\n}\n`
  },
})
StyleDictionary.registerFormat({
  name: 'json/cab-flat',
  format: ({ dictionary }) => JSON.stringify(flat(dictionary), null, 2) + '\n',
})
StyleDictionary.registerFormat({
  name: 'javascript/cab-module',
  format: ({ dictionary }) => {
    const entries = dictionary.allTokens.map(t => `  ${JSON.stringify(t.name)}: ${JSON.stringify(String(t.$value ?? t.value))},`).join('\n')
    return `/* Generated by Style Dictionary. Do not edit. */\nexport const tokens = {\n${entries}\n}\nexport default tokens\n`
  },
})
StyleDictionary.registerFormat({
  name: 'typescript/cab-module-declarations',
  format: ({ dictionary }) => {
    const keys = dictionary.allTokens.map(t => `  ${JSON.stringify(t.name)}: string`).join('\n')
    return `/* Generated by Style Dictionary. Do not edit. */\nexport declare const tokens: {\n${keys}\n}\nexport default tokens\n`
  },
})

export default {
  source: ['src/**/*.tokens.json'],
  usesDtcg: true,
  platforms: {
    css: {
      transformGroup: 'css',
      prefix: 'cab',
      buildPath: 'dist/',
      files: [{ destination: 'tokens.css', format: 'css/cab-variables', filter: t => !t.path[0].startsWith('palette') }],
    },
    js: {
      transformGroup: 'css',
      prefix: 'cab',
      buildPath: 'dist/',
      files: [
        { destination: 'tokens.js', format: 'javascript/cab-module', filter: t => t.path[0] !== 'palette' },
        { destination: 'tokens.d.ts', format: 'typescript/cab-module-declarations', filter: t => t.path[0] !== 'palette' },
        { destination: 'tokens.json', format: 'json/cab-flat', filter: t => t.path[0] !== 'palette' },
      ],
    },
  },
}
